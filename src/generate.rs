//! The generator of statements, per document 14 section 14.7 of the notes.
//!
//! One seed gives one SQL file, `run/gen/seed-<n>.sql`, and the differential runner runs it on
//! both servers in its three modes. The file has four parts:
//!
//! - The values: each edge value of document 06 section 6.16 cast to its type, again under each
//!   value of the settings that change the output, and some strings that the input function
//!   must refuse.
//! - The functions: calls to each immutable function and aggregate of `pg_catalog`, read from
//!   the catalog of the oracle, with edge values of the argument types.
//! - The schema: three tables with random rows.
//! - The queries: random queries over the schema, in the manner of SQLsmith.
//!
//! After the file, the logic checks run on each server alone. They compare a query with a
//! partitioned form of it (TLP) or with a form that the optimizer cannot change (NoREC), in the
//! manner of SQLancer. A check needs no oracle, so it finds wrong answers where both servers
//! would agree with a wrong plan. A check where either query fails is not counted.
//!
//! The harness has no dependencies, so the generators are written here and do not come from
//! `rudb-compat`. The walk over the grammar productions waits for the vendored grammar of
//! document 08.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};


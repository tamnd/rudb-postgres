#[derive(Debug, Clone)]
pub(crate) struct Options {
    pub(crate) seed: u64,
    /// The number of random queries, and the number of logic checks.
    pub(crate) count: usize,
}

/// The database of the logic checks. It is made again from `template0` before each run.
const DATABASE: &str = "rudb_postgres_gen";

/// The most calls for one function. The first call uses the first value of each type, and the
/// others are random.
const CALLS: usize = 3;

/// Generates the file of one seed, runs it through the differential runner and runs the logic
/// checks. Returns the number of statements that differ plus the number of failed checks.
pub(crate) fn run(
    root: &Path,
    oracle: &Server,
    other: &Server,
    options: &Options,
) -> Result<(usize, Json), String> {
    println!("seed {}", options.seed);
    let mut rng = Rng::new(options.seed);
    let functions = functions(oracle)?;
    let schema = schema(&mut rng);

    let mut file = String::new();
    let _ = writeln!(file, "-- Generated by rudb-postgres gen --seed {}.", options.seed);
    file.push_str("set statement_timeout = '10s';\n");
    let values = write_values(&mut file);
    let calls = write_calls(&mut file, &functions, &mut rng);
    file.push_str("\n-- The schema of the queries.\n");
    for statement in &schema {
        let _ = writeln!(file, "{statement};");
    }
    file.push_str("\n-- The queries.\n");
    for _ in 0..options.count {
        let _ = writeln!(file, "{};", query(&mut rng));
    }

    let dir = root.join("run").join("gen");
    std::fs::create_dir_all(&dir).map_err(|e| format!("cannot create {}: {e}", dir.display()))?;
    let path: PathBuf = dir.join(format!("seed-{}.sql", options.seed));
    std::fs::write(&path, &file).map_err(|e| format!("cannot write {}: {e}", path.display()))?;
    println!(
        "{} values, {calls} calls of {} functions, {} queries",
        values,
        functions.len(),
        options.count
    );
    let (differ, diff_json) = diff::run(&path, oracle, other, &diff::Options { rpg: false })?;

    let checks = checks(&mut rng, options.count);
    let mut failed = 0;
    let mut logic = Vec::new();
    for server in [oracle, other] {
        let (n, json) = run_checks(server, &schema, &checks)?;
        failed += n;
        logic.push(json);
    }

    let json = Json::object(vec![
        ("seed", Json::String(options.seed.to_string())),
        ("file", Json::String(path.display().to_string())),
        ("values", Json::Number(values as i64)),
        ("calls", Json::Number(calls as i64)),
        ("functions", Json::Number(functions.len() as i64)),
        ("queries", Json::Number(options.count as i64)),
        ("diff", diff_json),
        ("logic", Json::Array(logic)),
    ]);
    Ok((differ + failed, json))
}

/// SplitMix64. It is small, and the same seed gives the same file on every platform.
struct Rng(u64);

impl Rng {
    fn new(seed: u64) -> Rng {
        Rng(seed)
    }

    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9e37_79b9_7f4a_7c15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
        z ^ (z >> 31)
    }

    fn below(&mut self, n: usize) -> usize {
        (self.next() % n as u64) as usize
    }

    fn range(&mut self, low: i64, high: i64) -> i64 {
        low + (self.next() % (high - low + 1) as u64) as i64
    }

    fn chance(&mut self, percent: u64) -> bool {
        self.next() % 100 < percent
    }

    fn pick<'a, T>(&mut self, items: &'a [T]) -> &'a T {
        &items[self.below(items.len())]
    }
}

/// A string as an SQL literal.
fn quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', "''"))
}

/// A type name that means the catalog type with no type modifier. Quoted, `bit` and `char`
/// are the catalog types, and not `bit(1)` and `char(1)`.
fn type_name(typname: &str) -> String {
    format!("pg_catalog.\"{}\"", typname.replace('"', "\"\""))
}

